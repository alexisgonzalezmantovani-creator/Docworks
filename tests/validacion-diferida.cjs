// Regresión: los faltantes se validan al revisar, no colorean los pasos de carga.
// Ejecutar: node tests/validacion-diferida.cjs
const fs=require('node:fs');
const assert=require('node:assert/strict');
const path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'../src/Operaciones.tsx'),'utf8');
const start=source.indexOf('export function crearOperacionForm(deps)');
const end=source.indexOf('export function crearPapeleraView(deps)',start);
assert.ok(start>=0&&end>start,'Debe existir el formulario de operaciones');
const form=source.slice(start,end);
assert.match(form,/const camposFaltantes = \[\];/,'No pasar faltantes a campos durante la carga');
assert.match(form,/const faltantesDetalle = getCamposFaltantesDetalle\(data,perfil\)/,'Mantener validación documental');
assert.doesNotMatch(form,/step>total&&<div role="status"/,'Evitar duplicar estado del resumen en el formulario');
assert.match(form,/<PasoResumenFinal data=\{data\}/,'El resumen es el único responsable de mostrar faltantes');
assert.match(form,/document\.querySelectorAll\("\[data-falta\]"\)/,'Limpiar marcas heredadas');
assert.doesNotMatch(form,/setAttribute\("data-falta"/,'No reintroducir bordes rojos vía DOM');
assert.match(form,/<Btn onClick=\{avanzarConAviso\}>Continuar →<\/Btn>/,'Continuar siempre mantiene una sola acción');
assert.doesNotMatch(form,/Continuar igual →|setAvisoPaso\(true\)/,'No pedir un segundo toque para avanzar');
assert.match(form,/setStep\(function\(s\)\{return Math\.min\(s\+1,total\+1\);\}\)/,'Avanzar directamente sin bloquear por campos pendientes');
assert.match(form,/Revisar documento →/,'Conservar revisión final');
assert.match(form,/draftTieneContenido\(data\) \? \{ data:data/,'No persistir un formulario vacío como borrador');
assert.match(form,/dw-operation-save-slot/,'Indicador de guardado junto a siguiente');
assert.match(form,/if\(!initial && !draftTieneContenido\(dataRef\.current\)\) return;/,'Impedir guardar operaciones nuevas vacías');
const app=fs.readFileSync(path.join(__dirname,'../src/App.tsx'),'utf8');
const resumen=app.slice(app.indexOf('function PasoResumenFinal('),app.indexOf('function ',app.indexOf('function PasoResumenFinal(')+25));
assert.match(resumen,/aria-label="Datos para completar"/,'Mostrar lista accesible de faltantes solo en revisión');
assert.doesNotMatch(resumen,/Revisar faltantes \(/,'Evitar segundo botón de revisión');
const clauses=app.slice(app.indexOf('function StepClausulas('),app.indexOf('function StepBar('));
assert.match(clauses,/if\(activando\)\s*\{\s*if\(cfg\)onChange\(cfg\.campo\+"_id",id\);\s*setClausulaExpandida\(id\);/,'Activar cualquier cláusula abre su detalle');
assert.match(clauses,/className="dw-op-clause-expand"/,'El botón + tiene control propio');
assert.match(form,/lsRemove\("draftOperacion"\)/,'Eliminar borrador si se vacían los datos');
assert.match(app,/crearOperacionForm\(\{[^;]*lsRemove, lsSet/,'Inyectar limpieza de borrador desde App');
assert.match(app,/if\(k==="draftOperacion" && \(!v \|\| !v\.data \|\| !draftTieneContenido\(v\.data\)\)\)/,'Autoguardado limpia borradores vacíos');
assert.match(app,/Guardando en este dispositivo…/,'Indicar que el guardado en curso es local');
assert.match(app,/Borrador guardado en este dispositivo/,'No confundir autoguardado con sincronización');
assert.match(app,/No se pudo guardar el borrador en este dispositivo/,'Informar el alcance del error de guardado');
assert.doesNotMatch(source,/className="op-expediente-resumen"/,'No mostrar resumen de expediente en tarjetas');
assert.match(source,/Próximo paso sugerido:/,'Sugerir próximo paso al abrir documentos');
assert.match(app,/const STEPS_RES_ALQ=\[\{id:1,l:"Tipo"\},\{id:2,l:"Locador"\},\{id:3,l:"Locatario"\}/,'Reserva alquiler: locador antes de locatario');
assert.match(source,/if\(esResAlq\)\{[\s\S]{0,260}if\(step===2\)return <StepPersona[^\n]*prefix="locador"/,'Formulario de reserva: locador en paso 2');
assert.match(app,/function tituloRolForm[\s\S]{0,250}Locador \(propietario\)/,'Rótulo locador propietario');
console.log('OK: comprobaciones estáticas de validación diferida, borrador, cláusulas y navegación');
